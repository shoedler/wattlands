#!/usr/bin/env node
// Bakes the Castellum Rotae HUD's letter, icons and slot shapes from the mock's own code
// (hud_font.mjs, hud_parts.mjs) into assets/siege/hud/: hud_atlas.png (white where a glyph or a
// tinted icon pixel is lit, an icon's fixed-colour pixels in their colour) and hud_atlas.json
// (the rects and metrics). SiegeHudType and SiegeHudDraw read them, so the art and the game match.
//   node src/games/siege/art/hud_bake.mjs [--check]
// --check exits non-zero when the committed files differ from what this code makes.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateSync } from 'node:zlib';
import { writePng } from './png.mjs';
import { FACES, CHARS, bitmap } from './hud_font.mjs';
import { C, ICON, SHAPE, PEG } from './hud_parts.mjs';

const BAKE_VERSION = 2;
const repo = join(dirname(fileURLToPath(import.meta.url)), '../../../..');
const dir = join(repo, 'assets/siege/hud');
const pngPath = join(dir, 'hud_atlas.png');
const jsonPath = join(dir, 'hud_atlas.json');
const WIDTH = 1024;
const GUTTER = 1;

// Shelf packing, top to bottom, a gutter around every rect so nearest filtering never bleeds.
class Packer {
  constructor() {
    this.x = GUTTER;
    this.y = GUTTER;
    this.row = 0;
    this.cells = [];
  }
  place(w, h, paint) {
    if (this.x + w + GUTTER > WIDTH) {
      this.x = GUTTER;
      this.y += this.row + GUTTER;
      this.row = 0;
    }
    const cell = { x: this.x, y: this.y, w, h, paint };
    this.cells.push(cell);
    this.x += w + GUTTER;
    this.row = Math.max(this.row, h);
    return [cell.x, cell.y, w, h];
  }
}

const packer = new Packer();
const WHITE = [255, 255, 255];

const glyphRect = (b) =>
  packer.place(b.w, b.h, (put) => {
    for (let j = 0; j < b.h; j++) for (let i = 0; i < b.w; i++) if (b.data[j * b.w + i]) put(i, j, WHITE);
  });

const faces = {};
for (const [name, face] of Object.entries(FACES)) {
  const chars = face.rows ? Object.keys(face.rows) : CHARS;
  const glyphs = {};
  for (const ch of chars) {
    const b = bitmap(ch, face);
    if (b) glyphs[ch] = [...glyphRect(b), b.adv, b.pad ?? 0];
  }
  faces[name] = {
    cap: face.cap,
    track: face.track ?? 1,
    space: Math.round(face.cap * 0.42),
    shadow: face.cap >= 14,
    glyphs,
  };
}

// An icon's tint layer ('#', white) and its fixed layer (the other keys, in their colour).
const FIXED = { '+': C.stoneHi, o: C.ink, '=': C.bronze };
const layer = (rows, test, colourOf) => {
  const w = Math.max(...rows.map((r) => r.length));
  return packer.place(w, rows.length, (put) => {
    rows.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) if (test(row[i])) put(i, j, colourOf(row[i]));
    });
  });
};
const iconEntry = (rows) => {
  const out = { tint: layer(rows, (k) => k === '#', () => WHITE) };
  if (rows.some((r) => /[+o=]/.test(r))) out.fixed = layer(rows, (k) => k in FIXED, (k) => FIXED[k]);
  return out;
};
const icons = {};
for (const [name, rows] of Object.entries(ICON)) icons[name] = iconEntry(rows);
icons.peg = iconEntry(PEG);
// Slot shapes in Wl.SLOT_SHAPES order: circle, triangle, square, diamond.
const shapes = SHAPE.map((rows) => layer(rows, (k) => k === '#', () => WHITE));

const height = packer.y + packer.row + GUTTER;
const rgba = new Uint8Array(WIDTH * height * 4);
for (const cell of packer.cells) {
  cell.paint((i, j, c) => {
    const at = ((cell.y + j) * WIDTH + cell.x + i) * 4;
    rgba[at] = c[0];
    rgba[at + 1] = c[1];
    rgba[at + 2] = c[2];
    rgba[at + 3] = 255;
  });
}

const manifest = {
  generator: 'src/games/siege/art/hud_bake.mjs',
  bake_version: BAKE_VERSION,
  note: 'Generated by src/games/siege/art/hud_bake.mjs; do not edit by hand.',
  atlas: 'hud_atlas.png',
  size: [WIDTH, height],
  faces,
  icons,
  shapes,
};
const jsonText = JSON.stringify(manifest) + '\n';

// The RGBA of a PNG this tool wrote (png.mjs: 8 bit RGBA, no filtering).
function decode(path) {
  const buf = readFileSync(path);
  let at = 8;
  const idat = [];
  let w = 0;
  let h = 0;
  while (at < buf.length) {
    const len = buf.readUInt32BE(at);
    const type = buf.toString('ascii', at + 4, at + 8);
    if (type === 'IHDR') {
      w = buf.readUInt32BE(at + 8);
      h = buf.readUInt32BE(at + 12);
    } else if (type === 'IDAT') {
      idat.push(buf.subarray(at + 8, at + 8 + len));
    }
    at += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const out = new Uint8Array(w * h * 4);
  for (let y = 0; y < h; y++) raw.copy(out, y * w * 4, y * (w * 4 + 1) + 1, (y + 1) * (w * 4 + 1));
  return { w, h, data: out };
}

if (process.argv.includes('--check')) {
  const fail = (why) => {
    console.error(`hud atlas stale: ${why}. Run node src/games/siege/art/hud_bake.mjs`);
    process.exit(1);
  };
  if (!existsSync(pngPath) || !existsSync(jsonPath)) fail('a file is missing');
  if (readFileSync(jsonPath, 'utf8').replace(/\r\n/g, '\n') !== jsonText) fail('hud_atlas.json differs');
  const png = decode(pngPath);
  if (png.w !== WIDTH || png.h !== height) fail('hud_atlas.png has another size');
  if (Buffer.compare(Buffer.from(png.data), Buffer.from(rgba)) !== 0) fail('hud_atlas.png differs');
  console.log('hud atlas ok');
} else {
  mkdirSync(dir, { recursive: true });
  writePng(pngPath, WIDTH, height, rgba);
  writeFileSync(jsonPath, jsonText);
  console.log(`hud atlas -> ${dir} (${WIDTH} x ${height})`);
}
