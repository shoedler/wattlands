#!/usr/bin/env node
// Writes content/siege/maps/rotae.json from the same geometry the art is drawn from (world.mjs,
// scene.mjs), so the rules and the picture can't drift apart. tests/games/siege/art checks that
// the committed file matches this output.   node src/games/siege/art/export_map.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as W from './world.mjs';
import { WHEEL_X, WHEEL_Y, WHEEL_R, BALLISTA, ARROWS, CATAPULT, TAR_PUMP } from './scene.mjs';

const repo = join(dirname(fileURLToPath(import.meta.url)), '../../../..');
const out = join(repo, 'content/siege/maps/rotae.json');
const r2 = (v) => Math.round(v * 100) / 100;
W.build();

// The enemy path: the road from the camp (prog 0) to the bridgehead, then the bridge to the gate.
const L = W.roadLength(0);
const path = [];
for (let s = L; s > 0; s -= 4) {
  const p = W.roadPoint(0, s);
  path.push([r2(p.x), r2(p.y), r2(W.height(p.x, p.y))]);
}
path.push([44, 79, r2(W.height(44, 79))]);
const bridgeStart = path.length - 1;
path.push([44, 76, 0.3], [44, 63, 0.3]);
let len = 0;
const cum = [0];
for (let i = 1; i < path.length; i++) {
  len += Math.hypot(path[i][0] - path[i - 1][0], path[i][1] - path[i - 1][1]);
  cum.push(len);
}
const progAtRoadS = (s) => r2(L - s);

const map = {
  id: 'rotae',
  name: 'SIEGE_MAP_ROTAE',
  version: 2,
  note: 'Generated by src/games/siege/art/export_map.mjs; do not edit by hand.',
  units: 'metres; x east, y south (toward the camera), z up',
  camera: { k: W.CAMERA.k, ox: W.CAMERA.ox, oy: W.CAMERA.oy, depth: 'x + y + z (larger is nearer)' },
  fort: { min: [W.FORT_MIN.x, W.FORT_MIN.y], max: [W.FORT_MAX.x, W.FORT_MAX.y], wall_h_m: W.WALL_H },
  gate: { pos: [44, 62.5, 0], width_m: 7 },
  bridge: { from_prog_m: r2(cum[bridgeStart]), to_prog_m: r2(len), width_m: 7 },
  plaza: { center: [44, 81], radius_m: 8 },
  moat_edge_prog_m: r2(cum[bridgeStart]),
  path: { points: path, length_m: r2(len) },
  staging: [
    { id: 'camp', prog_m: 0 },
    { id: 'grove', prog_m: progAtRoadS(250) },
    { id: 'wadi', prog_m: progAtRoadS(150) },
    { id: 'arch', prog_m: progAtRoadS(95) },
  ],
  wheels: WHEEL_X.map((x, slot) => ({ slot, pos: [x, WHEEL_Y, WHEEL_R + 1.4], radius_m: WHEEL_R })),
  // station 0 is the mine (the old generator); 1..4 the weapons and the tar works
  stations: [
    { id: 0, name: 'mine', pos: [66.2, 11.2, 0] },
    { id: 1, name: 'ballista', pos: [BALLISTA.x, BALLISTA.y, BALLISTA.z + 6], muzzle_m: 7, yaw0_deg: 114 },
    { id: 2, name: 'onager', pos: [CATAPULT.x, CATAPULT.y, 17.2], muzzle_m: -1.4, yaw0_deg: 135 },
    { id: 3, name: 'arrows', pos: [ARROWS.x, ARROWS.y, ARROWS.z + 2.5], muzzle_m: 1.5, yaw0_deg: 143 },
    { id: 4, name: 'tar', pos: [TAR_PUMP.x, TAR_PUMP.y, TAR_PUMP.z] },
  ],
  pads: [
    { pad: 1, pos: [18, 59, 13.5] },
    { pad: 2, pos: [66, 59, 13.5] },
    { pad: 3, pos: [1.5, 30.5, 13.5] },
    { pad: 4, pos: [82.5, 34.5, 13.5] },
  ],
};

const text = JSON.stringify(map, null, 1).replace(/\[[\d\s.,-]+\]/g, (m) => m.replace(/\s+/g, ' ').replace('[ ', '[').replace(' ]', ']')) + '\n';
if (process.argv.includes('--check')) {
  const have = readFileSync(out, 'utf8');
  if (have !== text) {
    console.error('content/siege/maps/rotae.json is stale: run node src/games/siege/art/export_map.mjs');
    process.exit(1);
  }
  console.log('map ok');
} else {
  writeFileSync(out, text);
  console.log(`map: ${path.length} path points, ${len.toFixed(1)} m (road ${L.toFixed(1)} m) -> ${out}`);
}
