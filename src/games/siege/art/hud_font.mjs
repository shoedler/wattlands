// The Castellum Rotae letter: Roman square capitals with a broad-nib contrast, drawn from strokes
// at any pixel size, so the labels, the shop and the key numbers share one hand.
// A glyph is a list of polylines in a unit box (x 0..1, y 0..1 down) and optional serif points.

const arc = (cx, cy, rx, ry, a0, a1, n = 14) => {
  const out = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    out.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return out;
};

