export function measure(str, face) {
  let w = 0;
  for (const ch of str) {
    if (ch === ' ') {
      w += Math.round(face.cap * 0.42);
      continue;
    }
    const b = bitmap(ch, face);
    w += b ? b.adv : 0;
  }
  return Math.max(0, w - (face.track ?? 1));
}

// Calls put(x, y) for every lit pixel, with (x, y) the text's top left at cap height.
export function drawText(str, x, y, face, put) {
  let cx = x;
  for (const ch of str) {
    if (ch === ' ') {
      cx += Math.round(face.cap * 0.42);
      continue;
    }
    const b = bitmap(ch, face);
    if (!b) continue;
    for (let j = 0; j < b.h; j++) {
      for (let i = 0; i < b.w; i++) {
        if (b.data[j * b.w + i]) put(cx + i - b.pad, y + j - b.pad);
      }
    }
    cx += b.adv;
  }
  return cx;
}
