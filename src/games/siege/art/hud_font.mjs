const rowsBitmap = (rows, track) => {
  const w = rows[0].length;
  const data = new Uint8Array(w * rows.length);
  rows.forEach((row, j) => {
    for (let i = 0; i < w; i++) if (row[i] === '#') data[j * w + i] = 1;
  });
  return { w, h: rows.length, data, adv: w + track, pad: 0 };
};

const dist = (px, py, a, b) => {
  const vx = b[0] - a[0];
  const vy = b[1] - a[1];
  const l = vx * vx + vy * vy || 1e-6;
  const t = Math.max(0, Math.min(1, ((px - a[0]) * vx + (py - a[1]) * vy) / l));
  return Math.hypot(px - a[0] - t * vx, py - a[1] - t * vy);
};

const cache = new Map();
const TAILED = new Set([',', ';']);

// A glyph's bitmap at cap height `cap`, stems `thick` and hairlines `thin` px: {w, h, on(x, y)}.
export function bitmap(ch, face) {
  const key = `${ch}/${face.cap}/${face.aspect}/${face.thick}/${face.thin}`;
  if (cache.has(key)) return cache.get(key);
  if (face.rows) {
    const b = face.rows[ch] ? rowsBitmap(face.rows[ch], face.track ?? 1) : null;
    cache.set(key, b);
    return b;
  }
  const g = G[ch];
  if (!g) return null;
  const [strokes, serifs, wf] = g;
  const cap = face.cap;
  const w = Math.max(1, Math.round(cap * face.aspect * wf));
  const pad = 1;
  const bw = w + pad * 2;
  // a comma's tail hangs 2 px under the baseline, so it never reads as a full stop
  const tail = TAILED.has(ch);
  const bh = cap + pad * 2 + (tail ? 2 : 0);
  const data = new Uint8Array(bw * bh);
  const SS = 5;
  const X = (u) => pad + u * (w - 1) + 0.5;
  const Y = (v) => pad + v * (cap - 1) + 0.5;
  const segs = [];
  for (const line of strokes) {
    for (let i = 0; i + 1 < line.length; i++) {
      const a = [X(line[i][0]), Y(line[i][1])];
      const b = [X(line[i + 1][0]), Y(line[i + 1][1])];
      const len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1e-6;
      // the pen is held so a falling stroke (top left to bottom right) and an upright are thick
      const dx = (b[0] - a[0]) / len;
      const dy = (b[1] - a[1]) / len;
      const nib = Math.abs(dy * 0.92 + dx * 0.38);
      segs.push([a, b, (face.thin + (face.thick - face.thin) * Math.min(1, nib)) / 2]);
    }
  }
  if (tail) segs.push([[X(0.56), Y(1)], [X(0.24), Y(1) + 2], Math.max(face.thin, 1) / 2]);
  if (face.serif !== 0) {
    const sw = face.serif ?? Math.max(1, cap * 0.16);
    for (const s of serifs) {
      const c = [X(s[0]), Y(s[1])];
      segs.push([[c[0] - sw, c[1]], [c[0] + sw, c[1]], face.thin / 2]);
    }
  }
  for (let y = 0; y < bh; y++) {
    for (let x = 0; x < bw; x++) {
      let hits = 0;
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const px = x + (sx + 0.5) / SS;
          const py = y + (sy + 0.5) / SS;
          if (segs.some(([a, b, hw]) => dist(px, py, a, b) <= hw)) hits++;
        }
      }
      if (hits >= SS * SS * 0.46) data[y * bw + x] = 1;
    }
  }
  const out = { w: bw, h: bh, data, adv: w + (face.track ?? 1), pad };
  cache.set(key, out);
  return out;
}

