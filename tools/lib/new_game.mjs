#!/usr/bin/env node
// tools/lib/new_game.mjs: the logic behind tools/new_game and tools/new_game.ps1 (BRIEF 3.6,
// docs/OWNERSHIP.md TL1 and C17). Zero dependencies, Node 22.12+.
//
//   node tools/lib/new_game.mjs <id> [--root=<repo dir>] [--dry-run]
//
// Scaffolds game <id> from the template: copies src/games/_template/, content/_template/,
// assets/_template/ and tests/games/_template/ to the same places under <id>, rewriting every
// copied text file and file name:
//   _TEMPLATE_ and TEMPLATE_ -> <ID>_      (string keys: _TEMPLATE_LAP_DONE -> SIEGE_LAP_DONE)
//   _template               -> <id>        (paths and the game id: res://src/games/_template/)
//   Template                -> <Id>        (the class prefix: TemplateGame -> SiegeGame)
//   template_               -> <id>_       (file names: template_game.gd -> siege_game.gd)
// and setting game.json's title to the id in words ("big_fish" -> "Big Fish"). It copies no .uid,
// .import or .translation file (Godot makes fresh ones on the next import, so nothing collides with
// the template) and strips uid="uid://..." attributes from copied .tscn and .tres files. It also
// writes .github/workflows/game-<id>.yml, and docs/decisions/<id>.md, docs/credits.d/<id>.md and
// docs/changelog.d/<id>.md only where missing (a game session may write its decisions first).
//
// Exit codes: 0 scaffolded (or planned with --dry-run); 1 refused, nothing written: a target already
// exists (src/games/<id>/, content/<id>/, assets/<id>/, tests/games/<id>/ or the workflow), a
// class_name the scaffold would declare already exists in the project (for example "bigfish" after
// "big_fish": both give BigFish*), or the template is missing; 2 usage (no id, or an id that is not
// ^[a-z][a-z0-9_]*$).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const TEMPLATE_ID = '_template';
export const ID_PATTERN = /^[a-z][a-z0-9_]*$/;
/** Folders that hold one subfolder per game; the template's subfolder is copied in each. */
export const TREES = ['src/games', 'content', 'assets', 'tests/games'];
/** Generated by Godot's import: never copied. */
export const SKIPPED_EXTENSIONS = ['.uid', '.import', '.translation'];
/** Where Godot scripts with a class_name live (scanned for name collisions). */
export const SCRIPT_ROOTS = ['addons', 'src', 'tests', 'tools'];
const SKIPPED_DIRS = new Set(['.godot', '.git', 'node_modules', 'build', '.userdata', '.art_cache']);
const CLASS_NAME = /^class_name\s+([A-Za-z_][A-Za-z0-9_]*)/gm;
const TEXT_EXTENSIONS = new Set([
  '.gd', '.json', '.csv', '.md', '.tscn', '.tres', '.cfg', '.txt', '.mjs', '.js', '.cjs', '.yml',
  '.yaml', '.gdshader', '.shader', '.svg', '.html', '.ini', '.sh', '.ps1', '.gitkeep', '',
]);

const USAGE = `usage: tools/new_game <id> [--dry-run]      (tools/new_game.ps1 in PowerShell)
  <id>        lower case, ^[a-z][a-z0-9_]*$ (for example siege, tank, fishing)
  --dry-run   print what would be written and write nothing
  --root=<d>  repository root (default: this checkout)`;

/** "big_fish" -> "BigFish" (the class prefix). */
export function classPrefix(id) {
  return id
    .split('_')
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
}

/** "big_fish" -> "Big Fish" (game.json title). */
export function titleOf(id) {
  return id
    .split('_')
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(' ');
}

/**
 * Applies the template -> id rewriting rules, in order, to a text or a file name. Each rule matches
 * only at the start of a word (not after a letter or digit), so "test_template_rules.gd" becomes
 * "test_<id>_rules.gd" and "_is_template()" stays as it is.
 */
export function rewrite(text, id) {
  const up = `${id.toUpperCase()}_`;
  return text
    .replace(/(?<![A-Za-z0-9])_TEMPLATE_/g, up)
    .replace(/(?<![A-Za-z0-9_])TEMPLATE_/g, up)
    .replace(/(?<![A-Za-z0-9])_template(?![A-Za-z0-9])/g, id)
    .replace(/(?<![A-Za-z0-9])Template/g, classPrefix(id))
    .replace(/(?<![A-Za-z0-9])template_/g, `${id}_`);
}

/** Removes uid="uid://..." attributes (Godot assigns new ones on import). */
export function stripUids(text) {
  return text.replace(/[ \t]+uid="uid:\/\/[^"]*"/g, '');
}

export function validateId(id) {
  if (typeof id !== 'string' || id === '') return 'missing <id>';
  if (id === TEMPLATE_ID) return '"_template" is the template itself';
  if (!ID_PATTERN.test(id)) return `"${id}" is not a game id: use lower-case letters, digits and _, starting with a letter`;
  return '';
}

function isText(file, buf) {
  const ext = path.extname(file).toLowerCase();
  if (TEXT_EXTENSIONS.has(ext) || TEXT_EXTENSIONS.has(path.basename(file).toLowerCase())) return !buf.includes(0);
  return false;
}

function walk(dir, rel = '') {
  const out = [];
  for (const ent of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = rel ? `${rel}/${ent.name}` : ent.name;
    if (ent.isDirectory()) out.push(...walk(dir, r));
    else if (ent.isFile()) out.push(r);
  }
  return out.sort();
}

/** The class_names declared in a script's text. */
export function classNames(text) {
  return [...text.matchAll(CLASS_NAME)].map((m) => m[1]);
}

/** class_name -> rel path of its script, for every .gd under SCRIPT_ROOTS in `root`. */
export function projectClasses(root) {
  const out = new Map();
  const visit = (rel) => {
    let entries = [];
    try {
      entries = fs.readdirSync(path.join(root, rel), { withFileTypes: true });
    } catch {
      return;
    }
    for (const ent of entries) {
      const r = `${rel}/${ent.name}`;
      if (ent.isDirectory() && !SKIPPED_DIRS.has(ent.name)) visit(r);
      else if (ent.isFile() && ent.name.endsWith('.gd')) {
        for (const c of classNames(fs.readFileSync(path.join(root, r), 'utf8'))) if (!out.has(c)) out.set(c, r);
      }
    }
  };
  for (const top of SCRIPT_ROOTS) visit(top);
  return out;
}

function workflowText(id) {
  return `# CI for the ${id} game (written by tools/new_game; the ${id} game session owns this file).
# Nothing is pushed during a build, so GitHub never runs it there: each step must pass locally first.
name: game-${id}
on:
  push:
    branches: ['**']
  pull_request:
jobs:
  test:
    runs-on: ubuntu-latest
    timeout-minutes: 60
    env:
      WATTLANDS_NO_HW_CONTROL: '1'
      WATTLANDS_NO_NETWORK_INTEGRATIONS: '1'
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: '22'
      - name: Install Godot 4.7.2
        run: |
          curl -fsSL -o "$RUNNER_TEMP/godot.zip" https://github.com/godotengine/godot/releases/download/4.7.2-stable/Godot_v4.7.2-stable_linux.x86_64.zip
          unzip -q "$RUNNER_TEMP/godot.zip" -d "$RUNNER_TEMP/godot"
          echo "GODOT=$RUNNER_TEMP/godot/Godot_v4.7.2-stable_linux.x86_64" >> "$GITHUB_ENV"
      - name: Import
        run: tools/godot.sh --headless --path . --import || true
      - name: ${id} unit tests (BRIEF 7 strict rules)
        run: tools/run_tests --only=gut --gdir=res://tests/games/${id}
      - name: Script check
        run: tools/godot.sh --headless --path . -s tools/check_scripts.gd
`;
}

const FRAGMENTS = {
  'docs/decisions': (id) =>
    `# Decisions: ${id}\n\nShort ADRs for the ${id} game: date, decision, alternatives, reason. Game sessions keep their decisions here only; docs/DECISIONS.md holds the platform's.\n`,
  'docs/credits.d': (id) =>
    `# Credits: ${id}\n\nThird-party assets (art, audio, fonts) the ${id} game ships, with their licenses and sources.\n`,
  'docs/changelog.d': (id) => `# Changelog: ${id}\n\n- Scaffolded from the template with tools/new_game.\n`,
};

/**
 * Plans and (unless dryRun) writes the scaffold. Returns {code, message, written: [rel paths],
 * kept: [rel paths]}. Writes nothing when it refuses.
 */
export function scaffold(root, id, { dryRun = false } = {}) {
  const bad = validateId(id);
  if (bad) return { code: 2, message: `new_game: ${bad}\n${USAGE}`, written: [], kept: [] };
  const rel = (...p) => path.posix.join(...p);
  const templateMain = path.join(root, 'src', 'games', TEMPLATE_ID);
  if (!fs.existsSync(templateMain)) {
    return { code: 1, message: `new_game: no template at ${templateMain}`, written: [], kept: [] };
  }
  const workflow = rel('.github/workflows', `game-${id}.yml`);
  const targets = [...TREES.map((t) => rel(t, id)), workflow];
  const existing = targets.filter((t) => fs.existsSync(path.join(root, t)));
  if (existing.length > 0) {
    return {
      code: 1,
      message: `new_game: refusing to scaffold "${id}": ${existing.join(', ')} already exist${existing.length > 1 ? '' : 's'}. Nothing was written.`,
      written: [],
      kept: [],
    };
  }

  const files = []; // [{to, data}]
  for (const tree of TREES) {
    const src = path.join(root, tree, TEMPLATE_ID);
    if (!fs.existsSync(src)) continue;
    for (const f of walk(src)) {
      if (SKIPPED_EXTENSIONS.includes(path.extname(f).toLowerCase())) continue;
      const to = rel(tree, id, ...f.split('/').map((seg) => rewrite(seg, id)));
      const buf = fs.readFileSync(path.join(src, f));
      let data = buf;
      if (isText(f, buf)) {
        let text = rewrite(buf.toString('utf8'), id);
        if (/\.(tscn|tres)$/i.test(f)) text = stripUids(text);
        if (to === rel('src/games', id, 'game.json')) {
          text = text.replace(/("title"\s*:\s*)"[^"]*"/, `$1${JSON.stringify(titleOf(id))}`);
        }
        data = text;
      }
      files.push({ to, data });
    }
  }
  const existingClasses = projectClasses(root);
  const clashes = [];
  for (const f of files) {
    if (!f.to.endsWith('.gd') || typeof f.data !== 'string') continue;
    for (const c of classNames(f.data)) if (existingClasses.has(c)) clashes.push(`${c} (${existingClasses.get(c)})`);
  }
  if (clashes.length > 0) {
    return {
      code: 1,
      message: `new_game: refusing to scaffold "${id}": its class_name ${clashes.join(', ')} already exist${clashes.length > 1 ? '' : 's'} (class prefix ${classPrefix(id)}). Pick another id. Nothing was written.`,
      written: [],
      kept: [],
    };
  }
  files.push({ to: workflow, data: workflowText(id) });
  const kept = [];
  for (const [dir, make] of Object.entries(FRAGMENTS)) {
    const to = rel(dir, `${id}.md`);
    if (fs.existsSync(path.join(root, to))) kept.push(to);
    else files.push({ to, data: make(id) });
  }

  const written = files.map((f) => f.to);
  if (dryRun) {
    const lines = written.map((w) => `  write ${w}`).concat(kept.map((k) => `  keep  ${k}`));
    return { code: 0, message: `new_game: --dry-run, would scaffold "${id}":\n${lines.join('\n')}`, written: [], kept };
  }
  const created = [];
  try {
    for (const f of files) {
      const abs = path.join(root, f.to);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, f.data, { flag: 'wx' });
      created.push(abs);
    }
  } catch (e) {
    for (const abs of created.reverse()) fs.rmSync(abs, { force: true });
    for (const t of TREES) fs.rmSync(path.join(root, t, id), { recursive: true, force: true });
    return { code: 1, message: `new_game: writing failed (${e.message}); removed what was written`, written: [], kept };
  }
  const summary = [
    `new_game: scaffolded "${id}" (class prefix ${classPrefix(id)}, string keys ${id.toUpperCase()}_*): ${written.length} files.`,
    ...kept.map((k) => `new_game: kept existing ${k}`),
    // The renamed identifiers are shorter than the template's, so gdformat re-wraps a few lines.
    `next: uvx --from gdtoolkit==4.5.0 gdformat src/games/${id} tests/games/${id}, ` +
      `tools/godot.sh --headless --path . --import, then read docs/GAME_SDK.md and edit src/games/${id}/game.json`,
  ];
  return { code: 0, message: summary.join('\n'), written, kept };
}

export function main(argv) {
  let root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  let dryRun = false;
  const ids = [];
  for (const a of argv) {
    if (a === '--help' || a === '-h') {
      process.stdout.write(`${USAGE}\n`);
      return 0;
    } else if (a === '--dry-run') dryRun = true;
    else if (a.startsWith('--root=')) root = path.resolve(a.slice('--root='.length));
    else if (a.startsWith('-')) {
      process.stderr.write(`new_game: unknown option "${a}"\n${USAGE}\n`);
      return 2;
    } else ids.push(a);
  }
  if (ids.length > 1) {
    process.stderr.write(`new_game: give one id, got ${ids.join(' ')}\n${USAGE}\n`);
    return 2;
  }
  const r = scaffold(root, ids[0] ?? '', { dryRun });
  (r.code === 0 ? process.stdout : process.stderr).write(`${r.message}\n`);
  return r.code;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
